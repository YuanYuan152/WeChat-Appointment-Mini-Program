export function enrichAssessmentGuidance<T extends { id: string; reportIntro?: string }>(
  assessment: T
): T & Partial<ScaleGuidance> {
  const g = SCALE_GUIDANCE[assessment.id];
  if (!g) return assessment;
  return {
    ...assessment,
    instructions: g.instructions,
    features: g.features,
    // 报告页优先使用已有 reportIntro，否则回退到功能说明
    reportIntro: assessment.reportIntro || g.features,
  };
}
