export interface AgreementEmergencyContact {
  name: string
  relation: string
  phone: string
}

export function normalizeAgreementPhone(phone: string | null | undefined): string {
  return (phone || '').trim().replace(/[\s-]/g, '')
}

export function validateAgreementEmergencyContact(
  contact: AgreementEmergencyContact,
): string | null {
  const name = (contact.name || '').trim()
  const relation = (contact.relation || '').trim()
  const phone = normalizeAgreementPhone(contact.phone)
  if (!name) return '请填写紧急联系人姓名'
  if (!relation) return '请填写与紧急联系人的关系'
  if (!phone) return '请填写紧急联系人电话'
  if (!/^1\d{10}$/.test(phone) && !/^0\d{2,3}\d{7,8}$/.test(phone)) {
    return '请填写有效的紧急联系人电话'
  }
  return null
}

function fillPlaceholders(
  text: string,
  counselorName: string,
  priceYuan?: number,
  emergency?: Partial<AgreementEmergencyContact> | null,
): string {
  const name = (counselorName || '咨询师').trim() || '咨询师'
  const price = Math.max(0, Math.round(Number(priceYuan) || 0))
  const overtime = Math.max(1, Math.round(price / 5) || 1)
  const emergencyName = (emergency?.name || '').trim() || '__________________'
  const emergencyRelation = (emergency?.relation || '').trim() || '__________________'
  const emergencyPhone = (emergency?.phone || '').trim() || '__________________'
  return text
    .replaceAll('【咨询师姓名】', name)
    .replaceAll('【费用】', String(price))
    .replaceAll('【超时费用】', String(overtime))
    .replaceAll('【紧急联系人姓名】', emergencyName)
    .replaceAll('【紧急联系人关系】', emergencyRelation)
    .replaceAll('【紧急联系人电话】', emergencyPhone)
}

